'use strict';
/* Renders the static site into site/ (the exact contents of the public ZIP).
   Usage: node tools/build.js
   Output is plain HTML/CSS/JS with hashed asset filenames; nothing here runs on the server. */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const cfg = require('./site-config');
const layout = require('./layout');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'site');
const SRC = path.join(__dirname, 'src');
const FONT_CACHE = path.join(__dirname, 'build-cache', 'fonts');

const sha = (buf, n = 8) => crypto.createHash('sha256').update(buf).digest('hex').slice(0, n);
const write = (rel, content) => {
  const abs = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
};

// Clean output (allow-list rebuild: everything in site/ is generated).
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

// ---- Assets -----------------------------------------------------------------------
const assets = {};

// Fonts (optional: if the subset step was not run, fall back to the system stack).
let css = fs.readFileSync(path.join(SRC, 'site.css'), 'utf8');
const fontFiles = ['montserrat-800.woff2', 'montserrat-700.woff2', 'montserrat-600.woff2'];
const haveFonts = fontFiles.every((f) => fs.existsSync(path.join(FONT_CACHE, f)));
if (haveFonts) {
  for (const f of fontFiles) {
    const buf = fs.readFileSync(path.join(FONT_CACHE, f));
    const hashed = f.replace('.woff2', `.${sha(buf)}.woff2`);
    write(`assets/fonts/${hashed}`, buf);
    css = css.split(`/assets/fonts/${f}`).join(`/assets/fonts/${hashed}`);
    if (f.startsWith('montserrat-800')) assets.font800 = `/assets/fonts/${hashed}`;
  }
  write('assets/fonts/OFL.txt', fs.readFileSync(path.join(__dirname, 'vendor', 'fonts', 'OFL.txt')));
} else {
  // Strip the @font-face blocks so the stylesheet never requests a missing file.
  css = css.replace(/@font-face\s*\{[^}]*\}\s*/g, '');
  console.warn('WARN: subset fonts not found in tools/build-cache/fonts; building with the system font stack.');
}

const cssHash = sha(Buffer.from(css));
assets.css = `/assets/css/site.${cssHash}.css`;
write(`assets/css/site.${cssHash}.css`, css);

const js = fs.readFileSync(path.join(SRC, 'site.js'), 'utf8');
assets.js = `/assets/js/site.${sha(Buffer.from(js))}.js`;
write(assets.js.slice(1), js);

// Icons / favicons (unhashed, short cache).
for (const f of ['favicon.svg', 'favicon-32.png', 'apple-touch-icon.png']) {
  const p = path.join(SRC, 'img', f);
  if (fs.existsSync(p)) write(`assets/img/${f}`, fs.readFileSync(p));
  else console.warn(`WARN: missing ${f} (run node tools/make-icons.js)`);
}

// ---- Pages ------------------------------------------------------------------------
const pagesDir = path.join(__dirname, 'pages');
const pages = fs.readdirSync(pagesDir).filter((f) => f.endsWith('.js') && !f.startsWith('_')).sort()
  .map((f) => require(path.join(pagesDir, f)));

const sitemapUrls = [];
for (const p of pages) {
  const html = layout.page(p, assets);
  const rel = p.file || path.join(p.url.replace(/^\//, ''), 'index.html');
  write(rel, html);
  if (!p.noindex && p.inSitemap !== false) sitemapUrls.push(cfg.origin + p.url);
}

// ---- sitemap.xml / robots.txt --------------------------------------------------------
// lastmod is omitted on purpose: the owner's record has no verified per-page dates yet.
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapUrls.map((u) => `  <url><loc>${u}</loc></url>`).join('\n')}
</urlset>
`;
write('sitemap.xml', sitemap);
write('robots.txt', `User-agent: *
Allow: /

Sitemap: ${cfg.origin}/sitemap.xml
`);

// ---- .htaccess ---------------------------------------------------------------------
const bootHash = crypto.createHash('sha256').update(layout.INLINE_BOOT).digest('base64');
const csp = [
  "default-src 'self'",
  `script-src 'self' 'sha256-${bootHash}'`,
  "style-src 'self'",
  "img-src 'self'",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const host = cfg.origin.replace(/^https:\/\//, '');
const htaccess = `# Hard Knox Auto Glass — Apache/LiteSpeed configuration for Hostinger shared hosting.
# Generated by tools/build.js. Canonical host: ${cfg.origin}/
# Verify TLS is valid on both ${host} and www.${host} BEFORE uploading this file (see docs/deploy-rollback.md).

Options -Indexes
ErrorDocument 404 /404.html

AddDefaultCharset UTF-8
AddType font/woff2 .woff2
AddType image/svg+xml .svg
AddType application/json .json

<IfModule mod_rewrite.c>
RewriteEngine On

# 1. Force HTTPS on the canonical host (one hop).
RewriteCond %{HTTPS} !=on
RewriteRule ^ ${cfg.origin}%{REQUEST_URI} [R=301,L]

# 2. www -> bare host (one hop).
RewriteCond %{HTTP_HOST} ^www\\.${host.replace(/\./g, '\\.')}$ [NC]
RewriteRule ^ ${cfg.origin}%{REQUEST_URI} [R=301,L]

# 3. /path/index.html -> /path/
RewriteCond %{THE_REQUEST} \\s/+(.*/)?index\\.html[\\s?] [NC]
RewriteRule ^(.*/)?index\\.html$ /$1 [R=301,L]

# 4. Add the trailing slash to page directories.
RewriteCond %{REQUEST_FILENAME} -d
RewriteCond %{REQUEST_URI} !/$
RewriteRule ^(.*)$ /$1/ [R=301,L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "DENY"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
Header always set Content-Security-Policy "${csp}"
# HSTS is intentionally NOT set at launch. Enable only after HTTPS renewals have been observed (docs/deploy-rollback.md).

# Caching: editable HTML and policies revalidate quickly; hashed assets are immutable.
<FilesMatch "\\.html$">
  Header set Cache-Control "max-age=300, must-revalidate"
</FilesMatch>
<FilesMatch "\\.(xml|txt)$">
  Header set Cache-Control "max-age=3600, must-revalidate"
</FilesMatch>
<FilesMatch "\\.[0-9a-f]{8}\\.(css|js|woff2)$">
  Header set Cache-Control "public, max-age=31536000, immutable"
</FilesMatch>
<FilesMatch "^(favicon\\.svg|favicon-32\\.png|apple-touch-icon\\.png|OFL\\.txt)$">
  Header set Cache-Control "public, max-age=86400"
</FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json image/svg+xml
</IfModule>

# Block direct requests for dotfiles and source-control leftovers.
<FilesMatch "^\\.">
  Require all denied
</FilesMatch>
`;
write('.htaccess', htaccess);

// Expose the CSP string for the local preview server and the validation report.
fs.mkdirSync(path.join(__dirname, 'out'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'out', 'build-info.json'), JSON.stringify({
  builtAt: new Date().toISOString(), assets, csp, pages: pages.map((p) => p.url), sitemapUrls,
}, null, 2));

console.log(`Built ${pages.length} pages into site/ (${sitemapUrls.length} in sitemap).`);
console.log(`Assets: ${assets.css}, ${assets.js}${assets.font800 ? ', fonts: yes' : ', fonts: system stack'}`);
